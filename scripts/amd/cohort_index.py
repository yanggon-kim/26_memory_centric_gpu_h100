#!/usr/bin/env python3
"""Cohort index for results_published/ (CPU only; run on the login node after publishing a folder).

Every AMD result belongs to exactly one hardware cohort (MI300X, MI325X, MI350X) or is a labelled cross-cohort
analysis. Cohorts are never pooled. This script makes the cohort explicit in three places:

  results_published/<folder>/cohort.json   the folder's cohort, GPU, architecture, CU count and bandwidth per CU
  results_published/cohorts.json           machine-readable index
  results_published/COHORTS.md             human-readable index grouped by cohort, with the reviews that cite it

The cohort comes from the folder's launch_plan.json (`cohort`) when present, else from the folder name
(amd_<date>_<cohort>_...). Folders that name no cohort are cross-cohort and list the cohorts their files name.

  cohort_index.py [--repo .]
"""
import argparse
import json
from pathlib import Path
import re

# Vendor peak HBM bandwidth and CU counts; measured = E4 seqread4g at the full device (cubw jobs 483498, 483499,
# 496074), a streaming read with 4 GiB footprint. Bandwidth per CU = full-device bandwidth / CUs.
HW = {
    'mi300x': {'gpu': 'AMD Instinct MI300X', 'arch': 'gfx942', 'cus': 304, 'xcds': 8, 'cus_per_xcd': 38,
               'partitions': ['mi3008x', 'mi3001x'], 'hbm_peak_tb_s': 5.3, 'hbm_gib': 192, 'lds_kib_per_cu': 64,
               'measured_seqread_gb_s': 4563.5},
    'mi325x': {'gpu': 'AMD Instinct MI325X', 'arch': 'gfx942', 'cus': 304, 'xcds': 8, 'cus_per_xcd': 38,
               'partitions': ['mi3258x'], 'hbm_peak_tb_s': 6.0, 'hbm_gib': 256, 'lds_kib_per_cu': 64,
               'measured_seqread_gb_s': 4950.1},
    'mi350x': {'gpu': 'AMD Instinct MI350X', 'arch': 'gfx950', 'cus': 256, 'xcds': 8, 'cus_per_xcd': 32,
               'partitions': ['mi3508x', 'mi3501x'], 'hbm_peak_tb_s': 8.0, 'hbm_gib': 288, 'lds_kib_per_cu': 160,
               'measured_seqread_gb_s': 6416.2},
}
for h in HW.values():
    h['bw_per_cu_peak_gb_s'] = round(h['hbm_peak_tb_s'] * 1000 / h['cus'], 1)
    h['bw_per_cu_measured_gb_s'] = round(h['measured_seqread_gb_s'] / h['cus'], 1)
ORDER = ['mi300x', 'mi325x', 'mi350x', 'cross-cohort']


def classify(d):
    plan = d / 'launch_plan.json'
    info = {'folder': d.name}
    if plan.exists():
        p = json.loads(plan.read_text())
        info.update(cohort=p.get('cohort'), plan_kind=p.get('kind'), plan_version=p.get('version'),
                    partition=p.get('partition'), source='launch_plan.json')
    else:
        m = re.search(r'_(mi3\d\dx)', d.name)
        info.update(cohort=m.group(1) if m else 'cross-cohort', source='folder name' if m else 'no cohort in name')
    if info['cohort'] == 'cross-cohort':
        names = ' '.join(p.name for p in d.rglob('*'))
        info['cohorts_named'] = sorted(set(re.findall(r'mi3\d\dx', names)))
    m = re.search(r'job(\d+)', d.name)
    info['job'] = m.group(1) if m else None
    info['date'] = d.name.split('_')[1] if d.name.startswith('amd_') else None
    return info


def main(a):
    repo = Path(a.repo).resolve()
    pub = repo / 'results_published'
    docs = sorted((repo / 'docs/amd').glob('*.md'))
    texts = {p: p.read_text(errors='replace') for p in docs}
    rows = []
    for d in sorted(p for p in pub.iterdir() if p.is_dir()):
        info = classify(d)
        info['cited_by'] = [str(p.relative_to(repo)) for p in docs if d.name in texts[p]]
        rows.append(info)
        marker = {'cohort': info['cohort'], 'rule': 'cohorts are never pooled; cross-cohort rows compare matched '
                  'per-XCD CU fractions only', 'generated_by': 'scripts/amd/cohort_index.py'}
        if info['cohort'] in HW:
            marker['hardware'] = HW[info['cohort']]
        else:
            marker['cohorts_named'] = info.get('cohorts_named', [])
        (d / 'cohort.json').write_text(json.dumps(marker, indent=1) + '\n')
    (pub / 'cohorts.json').write_text(json.dumps({'hardware': HW, 'folders': rows}, indent=1) + '\n')
    L = ['# Published results by cohort', '',
         'Generated by `scripts/amd/cohort_index.py`; do not edit by hand. Each folder also carries a `cohort.json`.', '',
         '**Rules.** Every result belongs to one hardware cohort. Cohorts are never pooled. A comparison across cohorts',
         'is made only at matched per-XCD CU fractions and is labelled as such. Folder names follow',
         '`amd_<date>_<cohort>_<campaign>_job<id>`; a folder without a cohort in its name is a cross-cohort analysis.', '',
         '## Hardware', '',
         '| cohort | GPU | arch | CUs (XCDs x CUs) | LDS/CU | HBM peak | peak BW per CU | measured BW per CU |',
         '|---|---|---|---|---:|---:|---:|---:|']
    for c in ORDER[:-1]:
        h = HW[c]
        L.append(f"| **{c.upper()}** | {h['gpu']} | {h['arch']} | {h['cus']} ({h['xcds']} x {h['cus_per_xcd']}) | "
                 f"{h['lds_kib_per_cu']} KiB | {h['hbm_peak_tb_s']} TB/s | {h['bw_per_cu_peak_gb_s']} GB/s | "
                 f"{h['bw_per_cu_measured_gb_s']} GB/s |")
    L += ['', 'Measured BW per CU = E4 `seqread4g` at the full device / CUs (jobs 483498, 483499, 496074).']
    for c in ORDER:
        sel = [r for r in rows if r['cohort'] == c]
        if not sel:
            continue
        L += ['', f"## {c.upper() if c != 'cross-cohort' else 'Cross-cohort analyses'}", '',
              '| folder | job | date | plan | reviews citing it |', '|---|---|---|---|---|']
        for r in sel:
            plan = f"{r.get('plan_kind') or ''} {r.get('plan_version') or ''}".strip() or '-'
            if c == 'cross-cohort':
                plan = 'names ' + (', '.join(r.get('cohorts_named') or []) or 'none')
            cites = ', '.join(f"[{Path(p).stem}](../{p})" for p in r['cited_by']) or '-'
            L.append(f"| `{r['folder']}` | {r['job'] or '-'} | {r['date'] or '-'} | {plan} | {cites} |")
    (pub / 'COHORTS.md').write_text('\n'.join(L) + '\n')
    for c in ORDER:
        print(c, sum(r['cohort'] == c for r in rows))


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--repo', default=str(Path(__file__).resolve().parents[2]))
    main(p.parse_args())
